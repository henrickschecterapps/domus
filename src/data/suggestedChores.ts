/**
 * Detects the room category by checking name and id keywords,
 * returning the most relevant suggested chores list.
 */
export function getSuggestedChoresForRoom(roomOrName: { id?: string; name: string } | string): SuggestedChoreTemplate[] {
  const nameStr = (typeof roomOrName === 'string' ? roomOrName : `${roomOrName.id || ''} ${roomOrName.name}`).toLowerCase();

  if (nameStr.includes('cozinh') || nameStr.includes('copa') || nameStr.includes('despens')) {
    return ROOM_SUGGESTIONS_MAP.cozinha;
  }
  if (nameStr.includes('banheir') || nameStr.includes('lavabo') || nameStr.includes('wc') || nameStr.includes('toilet')) {
    return ROOM_SUGGESTIONS_MAP.banheiro;
  }
  if (nameStr.includes('sala') || nameStr.includes('living') || nameStr.includes('estar') || nameStr.includes('tv')) {
    return ROOM_SUGGESTIONS_MAP.sala;
  }
  if (nameStr.includes('quart') || nameStr.includes('suít') || nameStr.includes('suite') || nameStr.includes('hósped') || nameStr.includes('dorm')) {
    return ROOM_SUGGESTIONS_MAP.quarto;
  }
  if (nameStr.includes('lavand') || nameStr.includes('serviç') || nameStr.includes('servic') || nameStr.includes('varal')) {
    return ROOM_SUGGESTIONS_MAP.lavanderia;
  }
  if (nameStr.includes('escrit') || nameStr.includes('office') || nameStr.includes('estudo') || nameStr.includes('comput')) {
    return ROOM_SUGGESTIONS_MAP.escritorio;
  }
  if (nameStr.includes('varand') || nameStr.includes('sacad') || nameStr.includes('quintal') || nameStr.includes('jardim') || nameStr.includes('gourmet') || nameStr.includes('churrasq')) {
    return ROOM_SUGGESTIONS_MAP.varanda;
  }

  // Default fallback: combine essential general with popular chores
  return ROOM_SUGGESTIONS_MAP.geral;
}
